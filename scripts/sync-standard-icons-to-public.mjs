/**
 * Copy backend care-pathway gallery icons into Vite public assets.
 * Run from care-admin: node scripts/sync-standard-icons-to-public.mjs
 *
 * Prefers rich imported PNGs (local Available Care Plans look) and also
 * syncs generated standard SVGs as fallback.
 */
import { cpSync, existsSync, mkdirSync, readdirSync, writeFileSync } from 'fs'
import { join, dirname } from 'path'
import { fileURLToPath } from 'url'

const __dirname = dirname(fileURLToPath(import.meta.url))
const adminRoot = join(__dirname, '..')
const backendRoot = join(adminRoot, '..', 'careadmin-backend', 'uploads', 'care-pathway')
const backendImported = join(backendRoot, 'imported')
const backendStandard = join(backendRoot, 'standard')
const publicImported = join(adminRoot, 'public', 'care-plan-icons', 'imported')
const publicStandard = join(adminRoot, 'public', 'care-plan-icons', 'standard')
const generatedTs = join(adminRoot, 'src', 'features', 'service-users', 'care-plan', 'care-plan-icon-assets.generated.ts')

function syncDir(srcDir, destDir, extensions) {
  if (!existsSync(srcDir)) return []
  mkdirSync(destDir, { recursive: true })
  const files = readdirSync(srcDir).filter((f) => extensions.some((ext) => f.toLowerCase().endsWith(ext)))
  for (const file of files) {
    cpSync(join(srcDir, file), join(destDir, file))
  }
  return files
}

function titleFromSlug(slug) {
  return slug
    .split('-')
    .map((w) => w.charAt(0).toUpperCase() + w.slice(1))
    .join(' ')
}

const importedFiles = syncDir(backendImported, publicImported, ['.png', '.webp', '.jpg', '.jpeg'])
const standardFiles = syncDir(backendStandard, publicStandard, ['.svg'])

if (!importedFiles.length && !standardFiles.length) {
  console.error(`No icons found under ${backendRoot}`)
  console.error('Ensure careadmin-backend/uploads/care-pathway/{imported,standard} exist locally.')
  process.exit(1)
}

const importedSlugs = importedFiles.map((f) => f.replace(/\.[^.]+$/i, '')).sort()
const standardSlugs = standardFiles.map((f) => f.replace(/\.svg$/i, '')).sort()

const importedManifest = {
  source: 'careadmin-backend/uploads/care-pathway/imported',
  icons: importedFiles.map((file) => {
    const slug = file.replace(/\.[^.]+$/i, '')
    return { name: titleFromSlug(slug), slug, file: `/care-plan-icons/imported/${file}` }
  }),
}
const standardManifest = {
  source: 'careadmin-backend/uploads/care-pathway/standard',
  icons: standardFiles.map((file) => {
    const slug = file.replace(/\.svg$/i, '')
    return { name: titleFromSlug(slug), slug, file: `/care-plan-icons/standard/${file}` }
  }),
}

if (importedFiles.length) {
  writeFileSync(join(publicImported, 'manifest.json'), JSON.stringify(importedManifest, null, 2))
}
writeFileSync(join(publicStandard, 'manifest.json'), JSON.stringify(standardManifest, null, 2))

const ts = `/* Auto-generated by scripts/sync-standard-icons-to-public.mjs — do not edit by hand. */
export const CARE_PLAN_IMPORTED_ICON_FILES: Record<string, string> = {
${importedFiles
  .map((file) => {
    const slug = file.replace(/\.[^.]+$/i, '')
    return `  '${slug}': '/care-plan-icons/imported/${file}',`
  })
  .join('\n')}
}

export const CARE_PLAN_STANDARD_ICON_FILES: Record<string, string> = {
${standardFiles
  .map((file) => {
    const slug = file.replace(/\.svg$/i, '')
    return `  '${slug}': '/care-plan-icons/standard/${file}',`
  })
  .join('\n')}
}
`

writeFileSync(generatedTs, ts)

console.log(`Synced ${importedFiles.length} imported icon(s) → public/care-plan-icons/imported/`)
console.log(`Synced ${standardFiles.length} standard icon(s) → public/care-plan-icons/standard/`)
console.log(`Wrote ${generatedTs}`)

import { describe, expect, it } from 'vitest'
import type { InitialAssessmentRiskRecord } from '@/features/service-users/initial-assessment/types'
import { CARE_PLAN_META } from '@/features/service-users/care-plan/care-plan-form-meta'
import {
  applyManualRiskItems,
  deriveOtherRiskDisplayName,
  draftRiskMetaContainsOnlyManualIds,
  formatIaAssessmentSourceLine,
  manualRiskItemsFromDraft,
  mapIaRiskRecordsForCarePlanProfile,
  phraseIaRiskReasonFromPrompt,
  reasonIsNotRawQuestionOnly,
  selectIaRiskReason,
} from '@/features/service-users/care-plan/care-plan-risk-profile.util'

function iaRisk(
  partial: Partial<InitialAssessmentRiskRecord> &
    Pick<InitialAssessmentRiskRecord, 'id' | 'riskType' | 'description' | 'riskLevel'>,
): InitialAssessmentRiskRecord {
  return {
    submissionId: 'sub-1',
    serviceUserId: 'su-1',
    likelihood: partial.riskLevel,
    severity: partial.riskLevel,
    controlMeasures: null,
    residualRisk: null,
    reviewDate: null,
    status: 'OPEN',
    sourceSectionNumber: null,
    sourceQuestionId: null,
    sourceQuestionText: null,
    responsiblePersonId: null,
    autoGenerated: true,
    createdAt: '2026-08-25T00:00:00.000Z',
    updatedAt: '2026-08-25T00:00:00.000Z',
    ...partial,
  }
}

describe('selectIaRiskReason', () => {
  it('prefers answer value when available', () => {
    expect(
      selectIaRiskReason({
        description: 'Any fire safety risks identified?',
        sourceQuestionText: 'Any fire safety risks identified?',
        answerValue: 'Smoke alarms overdue for test; open flame risk in kitchen',
      }),
    ).toBe('Smoke alarms overdue for test; open flame risk in kitchen')
  })

  it('uses statement description when not a question prompt', () => {
    expect(
      selectIaRiskReason({
        description: 'Fall in last 12 months and mobility support required',
        sourceQuestionText: 'Any falls in the last 12 months?',
      }),
    ).toBe('Fall in last 12 months and mobility support required')
  })

  it('never displays only the raw question as the reason', () => {
    const q = 'Any fire safety risks identified?'
    const reason = selectIaRiskReason({
      description: q,
      sourceQuestionText: q,
    })
    expect(reason).not.toBe(q)
    expect(reason).not.toMatch(/\?$/)
    expect(reasonIsNotRawQuestionOnly(reason)).toBe(true)
    expect(reason).toBe('Fire safety risks identified')
  })

  it('phrases yes + question into a clinical reason', () => {
    const reason = selectIaRiskReason({
      description: 'Any skin concerns?',
      sourceQuestionText: 'Any skin concerns?',
      answerValue: 'Yes',
    })
    expect(reason).toBe('Yes — Skin concerns identified')
    expect(reasonIsNotRawQuestionOnly(reason)).toBe(true)
  })

  it('falls back to default when nothing useful exists', () => {
    expect(selectIaRiskReason({ description: '', sourceQuestionText: null })).toBe(
      'Identified from Initial Assessment',
    )
  })
})

describe('phraseIaRiskReasonFromPrompt', () => {
  it('converts fire safety question into a statement', () => {
    expect(phraseIaRiskReasonFromPrompt('Any fire safety risks identified?')).toBe(
      'Fire safety risks identified',
    )
  })
})

describe('deriveOtherRiskDisplayName', () => {
  it('maps Restricted to bed? → Bed Mobility Risk', () => {
    expect(deriveOtherRiskDisplayName('Restricted to bed?', 'Restricted to bed?')).toBe(
      'Bed Mobility Risk',
    )
  })

  it('maps Pain or distress identified? → Pain / Distress Risk', () => {
    expect(deriveOtherRiskDisplayName('Pain or distress identified?', null)).toBe(
      'Pain / Distress Risk',
    )
  })

  it('falls back to Other Risk when nothing useful can be derived', () => {
    expect(deriveOtherRiskDisplayName('', null)).toBe('Other Risk')
  })
})

describe('formatIaAssessmentSourceLine', () => {
  it('includes assessment date when provided', () => {
    expect(formatIaAssessmentSourceLine('2026-08-20T10:00:00.000Z')).toMatch(
      /^Source: Initial Assessment · /,
    )
  })

  it('omits date when missing', () => {
    expect(formatIaAssessmentSourceLine(null)).toBe('Source: Initial Assessment')
  })
})

describe('mapIaRiskRecordsForCarePlanProfile', () => {
  it('shows typed IA risks with statement reasons and source label', () => {
    const records = [
      iaRisk({
        id: 'risk-falls',
        riskType: 'FALLS',
        riskLevel: 'HIGH',
        description: 'Fall in last 12 months and mobility support required',
        sourceQuestionText: 'Any falls in the last 12 months?',
      }),
      iaRisk({
        id: 'risk-fire',
        riskType: 'FIRE',
        riskLevel: 'MEDIUM',
        description: 'Any fire safety risks identified?',
        sourceQuestionText: 'Any fire safety risks identified?',
      }),
    ]

    const display = mapIaRiskRecordsForCarePlanProfile(records, {
      submittedAt: '2026-08-20T10:00:00.000Z',
    })
    expect(display[0]).toMatchObject({
      name: 'Falls Risk',
      reason: 'Fall in last 12 months and mobility support required',
      source: 'initial_assessment',
    })
    expect(display[0].sourceLabel).toMatch(/^Source: Initial Assessment/)
    expect(display.find((d) => d.id === 'risk-fire')?.reason).toBe('Fire safety risks identified')
    expect(reasonIsNotRawQuestionOnly(display.find((d) => d.id === 'risk-fire')!.reason)).toBe(true)
  })

  it('names OTHER risks from question/description', () => {
    const display = mapIaRiskRecordsForCarePlanProfile([
      iaRisk({
        id: 'other-bed',
        riskType: 'OTHER',
        riskLevel: 'MEDIUM',
        description: 'Restricted to bed?',
        sourceQuestionText: 'Restricted to bed?',
      }),
    ])
    expect(display[0].name).toBe('Bed Mobility Risk')
    expect(display[0].reason).toBe('Restricted to bed identified')
  })

  it('omits CLOSED IA risks', () => {
    const display = mapIaRiskRecordsForCarePlanProfile([
      iaRisk({
        id: 'open',
        riskType: 'FALLS',
        riskLevel: 'HIGH',
        description: 'Active falls concern',
        status: 'OPEN',
      }),
      iaRisk({
        id: 'closed',
        riskType: 'MEDICATION',
        riskLevel: 'LOW',
        description: 'Resolved',
        status: 'CLOSED',
      }),
    ])
    expect(display.map((d) => d.id)).toEqual(['open'])
  })
})

describe('manual risk meta vs IA (publish invariant)', () => {
  it('does not save IA risk ids into __meta.riskItems', () => {
    const iaIds = new Set(['risk-falls', 'risk-skin'])
    const values = applyManualRiskItems({}, [{ id: 'manual-1', name: 'Custom care plan risk' }])
    expect(draftRiskMetaContainsOnlyManualIds(values, iaIds)).toBe(true)
    expect(values[CARE_PLAN_META.riskItems]).toContain('manual-1')
  })

  it('supports manual add/remove without touching IA records', () => {
    let values = applyManualRiskItems({}, [{ id: 'a', name: 'New risk' }])
    values = applyManualRiskItems(
      values,
      manualRiskItemsFromDraft(values).filter((r) => r.id !== 'a'),
    )
    expect(manualRiskItemsFromDraft(values)).toEqual([])
  })
})

import { describe, expect, it } from 'vitest'
import type { InitialAssessmentAction } from '@/features/service-users/initial-assessment/types'
import {
  cleanIaActionTitle,
  draftDoesNotContainIaActionIds,
  mapIaActionsForCarePlanProfile,
  selectIaActionReason,
} from '@/features/service-users/care-plan/care-plan-actions.util'

function iaAction(
  partial: Partial<InitialAssessmentAction> &
    Pick<InitialAssessmentAction, 'id' | 'title' | 'priority' | 'status'>,
): InitialAssessmentAction {
  return {
    submissionId: 'sub-1',
    serviceUserId: 'su-1',
    actionType: 'FALLS_ASSESSMENT',
    dueDate: null,
    notes: null,
    sourceSectionNumber: null,
    sourceQuestionId: null,
    sourceQuestionText: null,
    assignedToId: null,
    autoGenerated: true,
    createdAt: '2026-08-25T00:00:00.000Z',
    updatedAt: '2026-08-25T00:00:00.000Z',
    ...partial,
  }
}

describe('cleanIaActionTitle', () => {
  it('removes Follow-up: prefixes', () => {
    expect(cleanIaActionTitle('Follow-up: Medication verification')).toBe('Medication verification')
    expect(cleanIaActionTitle('Follow up - Fire safety')).toBe('Fire safety')
  })

  it('removes trailing follow-up wording', () => {
    expect(cleanIaActionTitle('Falls assessment follow-up')).toBe('Falls assessment')
    expect(cleanIaActionTitle('Fire safety follow-up')).toBe('Fire safety')
  })
})

describe('selectIaActionReason', () => {
  it('prefers notes over source question', () => {
    expect(
      selectIaActionReason({
        title: 'Falls assessment follow-up',
        notes: 'Arrange OT review for frame',
        sourceQuestionText: 'Any falls in the last 12 months?',
      }),
    ).toBe('Arrange OT review for frame')
  })

  it('omits reason when it would only repeat the cleaned title', () => {
    expect(
      selectIaActionReason({
        title: 'Falls assessment follow-up',
        notes: 'Falls assessment',
        sourceQuestionText: null,
      }),
    ).toBeNull()
  })

  it('phrases question prompts instead of showing raw question-only text', () => {
    const reason = selectIaActionReason({
      title: 'Fire safety',
      notes: null,
      sourceQuestionText: 'Any fire safety risks identified?',
    })
    expect(reason).not.toMatch(/\?$/)
    expect(reason).toContain('Fire safety risks')
  })
})

describe('mapIaActionsForCarePlanProfile', () => {
  it('maps open IA actions with clean titles', () => {
    const display = mapIaActionsForCarePlanProfile(
      [
        iaAction({
          id: 'act-falls',
          title: 'Falls assessment follow-up',
          priority: 'HIGH',
          status: 'OPEN',
          dueDate: '2026-09-01T00:00:00.000Z',
          notes: 'History of falls — mobility aid required',
        }),
        iaAction({
          id: 'act-fire',
          title: 'Follow-up: Fire safety follow-up',
          priority: 'MEDIUM',
          status: 'IN_PROGRESS',
          sourceQuestionText: 'Any fire safety risks identified?',
        }),
      ],
      { submittedAt: '2026-08-20T10:00:00.000Z' },
    )

    expect(display).toHaveLength(2)
    expect(display[0]).toMatchObject({
      id: 'act-falls',
      title: 'Falls assessment',
      priority: 'HIGH',
      status: 'OPEN',
      reason: 'History of falls — mobility aid required',
      source: 'initial_assessment',
    })
    expect(display[1].title).toBe('Fire safety')
    expect(display[0].dueDateLabel).toBeTruthy()
    expect(display[0].sourceLabel).toMatch(/^Source: Initial Assessment/)
  })

  it('returns empty list when there are no active IA actions', () => {
    expect(
      mapIaActionsForCarePlanProfile([
        iaAction({
          id: 'done',
          title: 'Done',
          priority: 'LOW',
          status: 'COMPLETED',
        }),
      ]),
    ).toEqual([])
  })
})

describe('draftDoesNotContainIaActionIds', () => {
  it('confirms IA action ids are not copied into care plan draft values', () => {
    const iaIds = new Set(['act-falls', 'act-fire'])
    const draft = {
      'clinical.field': 'value',
      '__meta.riskItems': JSON.stringify([{ id: 'manual-1', name: 'Manual risk' }]),
    }
    expect(draftDoesNotContainIaActionIds(draft, iaIds)).toBe(true)
  })
})

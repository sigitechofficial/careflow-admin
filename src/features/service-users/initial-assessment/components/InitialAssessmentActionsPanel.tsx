import { Loader2 } from 'lucide-react'
import { Button } from '@/shared/ui/button'
import {
  Select,
  SelectContent,
  SelectItem,
  SelectTrigger,
  SelectValue,
} from '@/shared/ui/select'
import { cn } from '@/shared/lib/utils'
import {
  useCreateInitialAssessmentAction,
  useInitialAssessmentActions,
  useRegenerateInitialAssessmentActions,
  useUpdateInitialAssessmentAction,
} from '@/features/service-users/initial-assessment/hooks/useInitialAssessmentEnterprise'
import type {
  InitialAssessmentActionPriority,
  InitialAssessmentActionStatus,
  InitialAssessmentActionType,
} from '@/features/service-users/initial-assessment/types'

const PRIORITY_CLASS: Record<InitialAssessmentActionPriority, string> = {
  LOW: 'bg-muted text-muted-foreground',
  MEDIUM: 'bg-sky-100 text-sky-900 dark:bg-sky-950 dark:text-sky-200',
  HIGH: 'bg-amber-100 text-amber-900 dark:bg-amber-950 dark:text-amber-200',
  URGENT: 'bg-red-100 text-red-900 dark:bg-red-950 dark:text-red-200',
}

const STATUS_CLASS: Record<InitialAssessmentActionStatus, string> = {
  OPEN: 'bg-teal-100 text-teal-900 dark:bg-teal-950 dark:text-teal-200',
  IN_PROGRESS: 'bg-blue-100 text-blue-900',
  COMPLETED: 'bg-emerald-100 text-emerald-900',
  CANCELLED: 'bg-muted text-muted-foreground',
}

type Props = {
  serviceUserId: string
  submissionId: string | null
  canUpdate: boolean
  editable: boolean
}

export function InitialAssessmentActionsPanel({
  serviceUserId,
  submissionId,
  canUpdate,
  editable,
}: Props) {
  const actionsQuery = useInitialAssessmentActions(serviceUserId, submissionId)
  const createMutation = useCreateInitialAssessmentAction(serviceUserId, submissionId ?? '')
  const updateMutation = useUpdateInitialAssessmentAction(serviceUserId, submissionId ?? '')
  const regenerateMutation = useRegenerateInitialAssessmentActions(serviceUserId, submissionId ?? '')

  const actions = actionsQuery.data ?? []
  const openCount = actions.filter((a) => a.status === 'OPEN' || a.status === 'IN_PROGRESS').length

  const addManual = () => {
    if (!submissionId || !canUpdate) return
    void createMutation.mutateAsync({
      title: 'Follow-up action',
      actionType: 'OTHER' as InitialAssessmentActionType,
      priority: 'MEDIUM',
      dueDate: new Date(Date.now() + 14 * 86400000).toISOString().slice(0, 10),
    })
  }

  return (
    <div className="rounded-xl border border-border bg-card shadow-sm">
      <div className="flex flex-wrap items-center justify-between gap-2 border-b px-4 py-3">
        <div>
          <h3 className="text-sm font-semibold">Action register</h3>
          <p className="text-xs text-muted-foreground">
            §14.2 — {openCount} open action{openCount === 1 ? '' : 's'}
            {actions.length ? ` · ${actions.length} total` : ''}
          </p>
        </div>
        {canUpdate && submissionId ? (
          <div className="flex flex-wrap gap-2">
            <Button
              type="button"
              size="sm"
              variant="outline"
              disabled={regenerateMutation.isPending}
              onClick={() => void regenerateMutation.mutateAsync()}
            >
              Sync from flags
            </Button>
            <Button type="button" size="sm" disabled={createMutation.isPending} onClick={() => void addManual()}>
              Add action
            </Button>
          </div>
        ) : null}
      </div>

      {actionsQuery.isLoading ? (
        <div className="flex items-center gap-2 px-4 py-8 text-sm text-muted-foreground">
          <Loader2 className="h-4 w-4 animate-spin" />
          Loading actions…
        </div>
      ) : actions.length === 0 ? (
        <p className="px-4 py-8 text-center text-sm text-muted-foreground">
          No actions yet. Submit the assessment to auto-generate from flagged answers, or add manually.
        </p>
      ) : (
        <div className="overflow-x-auto">
          <table className="w-full min-w-[640px] border-collapse text-sm">
            <thead>
              <tr className="border-b bg-muted/40 text-left text-xs uppercase text-muted-foreground">
                <th className="px-3 py-2">Action</th>
                <th className="px-3 py-2">Priority</th>
                <th className="px-3 py-2">Due</th>
                <th className="px-3 py-2">Status</th>
                <th className="px-3 py-2">Source</th>
              </tr>
            </thead>
            <tbody>
              {actions.map((action) => (
                <tr key={action.id} className="border-b">
                  <td className="px-3 py-2">
                    <div className="font-medium">{action.title}</div>
                    {action.autoGenerated ? (
                      <span className="text-[10px] uppercase text-muted-foreground">Auto</span>
                    ) : null}
                  </td>
                  <td className="px-3 py-2">
                    <span
                      className={cn(
                        'rounded-full px-2 py-0.5 text-xs font-semibold uppercase',
                        PRIORITY_CLASS[action.priority],
                      )}
                    >
                      {action.priority}
                    </span>
                  </td>
                  <td className="px-3 py-2 text-muted-foreground">
                    {action.dueDate ? action.dueDate.slice(0, 10) : '—'}
                  </td>
                  <td className="px-3 py-2">
                    {canUpdate && editable ? (
                      <Select
                        value={action.status}
                        onValueChange={(v) =>
                          void updateMutation.mutateAsync({
                            actionId: action.id,
                            body: { status: v as InitialAssessmentActionStatus },
                          })
                        }
                      >
                        <SelectTrigger className="h-8 w-[130px]">
                          <SelectValue />
                        </SelectTrigger>
                        <SelectContent>
                          <SelectItem value="OPEN">Open</SelectItem>
                          <SelectItem value="IN_PROGRESS">In progress</SelectItem>
                          <SelectItem value="COMPLETED">Completed</SelectItem>
                          <SelectItem value="CANCELLED">Cancelled</SelectItem>
                        </SelectContent>
                      </Select>
                    ) : (
                      <span
                        className={cn(
                          'rounded-full px-2 py-0.5 text-xs font-semibold uppercase',
                          STATUS_CLASS[action.status],
                        )}
                      >
                        {action.status.replace('_', ' ')}
                      </span>
                    )}
                  </td>
                  <td className="px-3 py-2 text-xs text-muted-foreground">
                    {action.sourceSectionNumber ? `§${action.sourceSectionNumber}` : '—'}
                    {action.sourceQuestionText ? (
                      <span className="mt-0.5 block max-w-[200px] truncate">{action.sourceQuestionText}</span>
                    ) : null}
                  </td>
                </tr>
              ))}
            </tbody>
          </table>
        </div>
      )}
    </div>
  )
}

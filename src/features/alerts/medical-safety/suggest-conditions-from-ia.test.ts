import { describe, expect, it } from 'vitest'
import type { InitialAssessmentRiskRecord } from '@/features/service-users/initial-assessment/types'
import { suggestConditionCodesFromSources } from '@/features/alerts/medical-safety/suggest-conditions-from-ia'

function iaRisk(
  overrides: Partial<InitialAssessmentRiskRecord> &
    Pick<InitialAssessmentRiskRecord, 'riskType' | 'description'>,
): InitialAssessmentRiskRecord {
  return {
    id: overrides.id ?? 'r1',
    submissionId: 'sub-1',
    serviceUserId: 'su-1',
    riskType: overrides.riskType,
    description: overrides.description,
    likelihood: 'MEDIUM',
    severity: 'MEDIUM',
    riskLevel: overrides.riskLevel ?? 'HIGH',
    controlMeasures: overrides.controlMeasures ?? null,
    residualRisk: null,
    reviewDate: null,
    status: overrides.status ?? 'OPEN',
    sourceSectionNumber: null,
    sourceQuestionId: null,
    sourceQuestionText: overrides.sourceQuestionText ?? null,
    responsiblePersonId: null,
    autoGenerated: false,
    createdAt: '2026-01-01T00:00:00.000Z',
    updatedAt: '2026-01-01T00:00:00.000Z',
  }
}

describe('suggestConditionCodesFromSources', () => {
  it('suggests catalogue codes from meaningful IA risks and DoLS', () => {
    const codes = suggestConditionCodesFromSources({
      iaRisksReady: true,
      iaRiskRecords: [
        iaRisk({ riskType: 'FALLS', description: 'Two falls this year — use frame' }),
        iaRisk({ riskType: 'CHOKING', description: 'Soft diet; supervise meals' }),
        iaRisk({ riskType: 'NUTRITION', description: 'Low intake — fortified drinks' }),
      ],
      hasDolsRecord: true,
    })
    expect(codes).toEqual(
      expect.arrayContaining([
        'HIGH_RISK_FALLS',
        'CHOKING_RISK',
        'DYSPHAGIA',
        'NUTRITION_HYDRATION',
        'COMMUNITY_DOLS',
      ]),
    )
  })

  it('ignores question-only IA risks and already-active codes', () => {
    const codes = suggestConditionCodesFromSources({
      iaRisksReady: true,
      iaRiskRecords: [
        iaRisk({
          riskType: 'FALLS',
          description: 'Falls in last 12 months?',
          sourceQuestionText: 'Falls in last 12 months?',
        }),
      ],
      fallsLast12Months: true,
      alreadyActiveCodes: ['HIGH_RISK_FALLS'],
    })
    expect(codes).not.toContain('HIGH_RISK_FALLS')
  })

  it('returns empty when sources are unread or empty', () => {
    expect(
      suggestConditionCodesFromSources({
        iaRisksReady: false,
        iaRiskRecords: [
          iaRisk({ riskType: 'FALLS', description: 'History of falls' }),
        ],
      }),
    ).toEqual([])
    expect(
      suggestConditionCodesFromSources({
        iaRisksReady: true,
        iaRiskRecords: [],
      }),
    ).toEqual([])
  })
})

import { describe, expect, it } from 'vitest'
import type { InitialAssessmentRiskRecord } from '@/features/service-users/initial-assessment/types'
import { buildClinicalGates } from '@/features/alerts/medical-safety/MedicalAlertsClinicalBody'
import {
  hasViewableSuggestion,
  isActiveFlashMessageText,
  isMeaningfulSupportingText,
  resolveSuggestion,
  supportingInfoFromIaRisk,
} from '@/features/alerts/medical-safety/medical-alert-suggestions'

function iaRisk(
  overrides: Partial<InitialAssessmentRiskRecord> &
    Pick<InitialAssessmentRiskRecord, 'riskType' | 'description'>,
): InitialAssessmentRiskRecord {
  return {
    id: overrides.id ?? 'r1',
    submissionId: 'sub-1',
    serviceUserId: 'su-1',
    riskType: overrides.riskType,
    description: overrides.description,
    likelihood: 'MEDIUM',
    severity: 'MEDIUM',
    riskLevel: overrides.riskLevel ?? 'HIGH',
    controlMeasures: overrides.controlMeasures ?? null,
    residualRisk: null,
    reviewDate: null,
    status: overrides.status ?? 'OPEN',
    sourceSectionNumber: null,
    sourceQuestionId: null,
    sourceQuestionText: overrides.sourceQuestionText ?? null,
    responsiblePersonId: null,
    autoGenerated: false,
    createdAt: '2026-01-01T00:00:00.000Z',
    updatedAt: '2026-01-01T00:00:00.000Z',
  }
}

const ALL_GATE_IDS = [
  'capabilities',
  'general-alert',
  'communication',
  'diabetes',
  'dietary',
  'palliative',
  'behaviour',
  'falls',
  'dols',
  'choking',
  'copd',
  'dnacpr',
  'risk-level',
  'allergies',
] as const

describe('medical alert suggestion evidence rules', () => {
  it('rejects empty, question, title, stub, and placeholder text as supporting information', () => {
    expect(isMeaningfulSupportingText(null)).toBe(false)
    expect(isMeaningfulSupportingText('')).toBe(false)
    expect(isMeaningfulSupportingText('  ')).toBe(false)
    expect(isMeaningfulSupportingText('Is the service user at risk of falling?')).toBe(false)
    expect(isMeaningfulSupportingText('Falls in last 12 months?')).toBe(false)
    expect(isMeaningfulSupportingText('Falls risk')).toBe(false)
    expect(isMeaningfulSupportingText('Yes')).toBe(false)
    expect(isMeaningfulSupportingText('No active flash message')).toBe(false)
    expect(isMeaningfulSupportingText('History of two falls in March')).toBe(true)
  })

  it('resolveSuggestion requires both indication and real evidence', () => {
    expect(resolveSuggestion('YES', null).suggestion).toBe('UNKNOWN')
    expect(resolveSuggestion('NO', 'Falls risk').suggestion).toBe('UNKNOWN')
    expect(resolveSuggestion('YES', 'No active flash message').suggestion).toBe('UNKNOWN')
    expect(resolveSuggestion('YES', 'History of falls').suggestion).toBe('YES')
    expect(resolveSuggestion('NO', 'DNACPR status confirmation: not in place').suggestion).toBe('NO')
  })

  it('IA risk supporting info ignores question-only descriptions', () => {
    expect(
      supportingInfoFromIaRisk(
        iaRisk({
          riskType: 'FALLS',
          description: 'Falls in last 12 months?',
          sourceQuestionText: 'Falls in last 12 months?',
        }),
      ),
    ).toBeNull()
    expect(
      supportingInfoFromIaRisk(
        iaRisk({
          riskType: 'FALLS',
          description: 'Unsteady gait; requires walking frame',
        }),
      ),
    ).toMatch(/Unsteady gait/)
  })

  it('isActiveFlashMessageText rejects empty-flash API status copy', () => {
    expect(isActiveFlashMessageText(null)).toBe(false)
    expect(isActiveFlashMessageText('No active flash message')).toBe(false)
    expect(isActiveFlashMessageText('Two carers for transfers')).toBe(true)
  })
})

describe('buildClinicalGates standardised suggestions — all 14 alerts', () => {
  it('explicit YES + evidence → suggestion YES + View suggestion for every mapped source', () => {
    const gates = buildClinicalGates({
      serviceUserId: 'su-1',
      iaRisksReady: true,
      iaRiskRecords: [
        iaRisk({
          riskType: 'MOVING_HANDLING',
          description: 'Full hoist transfers; two carers',
        }),
        iaRisk({
          riskType: 'OTHER',
          description: 'Communication aid required — non-verbal aphasia support',
        }),
        iaRisk({
          riskType: 'OTHER',
          description: 'Behaviour support plan for aggression during personal care',
        }),
        iaRisk({ riskType: 'FALLS', description: 'History of falls — use mobility aid' }),
        iaRisk({ riskType: 'CHOKING', description: 'Soft diet only; supervise meals' }),
        iaRisk({ riskType: 'NUTRITION', description: 'Nutrition risk — fortified fluids' }),
      ],
      conditionsReady: true,
      hasDiabetesCondition: true,
      hasPalliativeCondition: true,
      hasCopdCondition: true,
      flashReady: true,
      flashMessage: 'Aggressive behaviour overnight — two-person approach',
      documentsReady: true,
      dolsSummaries: ['Current authorisation · Issued 2026-01-02 · Notes: community DoLS'],
      dnacprStatus: 'IN_PLACE',
      dnacprSummary: 'Location: Fridge folder',
      allergySourceReady: true,
      allergyItems: [
        {
          id: 'allergy-1',
          severity: 'HIGH',
          title: 'Latex',
          description: 'Contact reaction',
          sourceLabel: 'Service user allergies',
          updatedAt: null,
          link: null,
          group: 'allergies',
          kind: 'clinical',
        },
      ],
      riskLevelName: 'High',
      isHighRisk: true,
    })

    const expectedYes = [
      'capabilities',
      'general-alert',
      'communication',
      'diabetes',
      'dietary',
      'palliative',
      'behaviour',
      'falls',
      'dols',
      'choking',
      'copd',
      'dnacpr',
      'risk-level',
      'allergies',
    ] as const

    for (const id of expectedYes) {
      const gate = gates.find((g) => g.id === id)
      expect(gate?.suggestion, id).toBe('YES')
      expect(hasViewableSuggestion(gate!), id).toBe(true)
      expect(gate?.suggestionDetail, id).toBeTruthy()
    }
    expect(gates.map((g) => g.id)).toEqual([...ALL_GATE_IDS])
  })

  it('explicit NO + evidence → suggestion NO for DNACPR and non-high Risk Level', () => {
    const gates = buildClinicalGates({
      serviceUserId: 'su-1',
      dnacprStatus: 'NOT_IN_PLACE',
      riskLevelName: 'Low',
      isHighRisk: false,
    })
    expect(gates.find((g) => g.id === 'dnacpr')?.suggestion).toBe('NO')
    expect(hasViewableSuggestion(gates.find((g) => g.id === 'dnacpr')!)).toBe(true)
    expect(gates.find((g) => g.id === 'risk-level')?.suggestion).toBe('NO')
    expect(hasViewableSuggestion(gates.find((g) => g.id === 'risk-level')!)).toBe(true)
  })

  it('missing / empty / loaded-but-empty sources → UNKNOWN and no View suggestion (never invented NO)', () => {
    const gates = buildClinicalGates({
      serviceUserId: 'su-1',
      iaRisksReady: true,
      iaRiskRecords: [],
      conditionsReady: true,
      hasDiabetesCondition: false,
      hasCopdCondition: false,
      hasPalliativeCondition: false,
      flashReady: true,
      flashMessage: null,
      documentsReady: true,
      dolsSummaries: [],
      dnacprStatus: 'UNKNOWN',
      allergySourceReady: true,
      allergyItems: [],
      riskLevelName: null,
      isHighRisk: false,
    })

    for (const id of ALL_GATE_IDS) {
      const gate = gates.find((g) => g.id === id)!
      expect(gate.suggestion, id).toBe('UNKNOWN')
      expect(hasViewableSuggestion(gate), id).toBe(false)
      expect(gate.suggestionDetail, id).toBeNull()
    }
  })

  it('question-only IA and flash placeholder → no suggestion', () => {
    const questionOnly = buildClinicalGates({
      serviceUserId: 'su-1',
      iaRisksReady: true,
      iaRiskRecords: [
        iaRisk({
          riskType: 'FALLS',
          description: 'Falls in last 12 months?',
          sourceQuestionText: 'Falls in last 12 months?',
        }),
        iaRisk({
          riskType: 'CHOKING',
          description: 'Any choking risks identified?',
          sourceQuestionText: 'Any choking risks identified?',
        }),
        iaRisk({
          riskType: 'MOVING_HANDLING',
          description: 'Does the service user need moving and handling support?',
          sourceQuestionText: 'Does the service user need moving and handling support?',
        }),
      ],
    })
    expect(questionOnly.find((g) => g.id === 'falls')?.suggestion).toBe('UNKNOWN')
    expect(questionOnly.find((g) => g.id === 'choking')?.suggestion).toBe('UNKNOWN')
    expect(questionOnly.find((g) => g.id === 'capabilities')?.suggestion).toBe('UNKNOWN')
    expect(hasViewableSuggestion(questionOnly.find((g) => g.id === 'falls')!)).toBe(false)

    const placeholder = buildClinicalGates({
      serviceUserId: 'su-1',
      flashReady: true,
      flashMessage: 'No active flash message',
    })
    expect(placeholder.find((g) => g.id === 'general-alert')?.suggestion).toBe('UNKNOWN')
    expect(hasViewableSuggestion(placeholder.find((g) => g.id === 'general-alert')!)).toBe(false)
  })

  it('unread / not-ready sources stay UNKNOWN even when payload is present', () => {
    const gates = buildClinicalGates({
      serviceUserId: 'su-1',
      iaRisksReady: false,
      iaRiskRecords: [
        iaRisk({ riskType: 'FALLS', description: 'History of falls — frame required' }),
      ],
      conditionsReady: false,
      hasDiabetesCondition: true,
      flashReady: false,
      flashMessage: 'Should not apply while unread',
      documentsReady: false,
      dolsSummaries: ['Current authorisation · Notes: DoLS'],
      dnacprStatus: 'IN_PLACE',
      dnacprSummary: 'Location: Fridge',
      allergySourceReady: false,
      allergyItems: [
        {
          id: 'allergy-1',
          severity: 'HIGH',
          title: 'Latex',
          description: 'Contact reaction',
          sourceLabel: 'Service user allergies',
          updatedAt: null,
          link: null,
          group: 'allergies',
          kind: 'clinical',
        },
      ],
    })
    expect(gates.find((g) => g.id === 'falls')?.suggestion).toBe('UNKNOWN')
    expect(gates.find((g) => g.id === 'diabetes')?.suggestion).toBe('UNKNOWN')
    expect(gates.find((g) => g.id === 'general-alert')?.suggestion).toBe('UNKNOWN')
    expect(gates.find((g) => g.id === 'dols')?.suggestion).toBe('UNKNOWN')
    expect(gates.find((g) => g.id === 'dnacpr')?.suggestion).toBe('UNKNOWN')
    expect(gates.find((g) => g.id === 'allergies')?.suggestion).toBe('UNKNOWN')
  })
})
